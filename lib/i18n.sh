hkz_pick_lang() {
  echo ""
  echo "  ----------------------------------------"
  echo "  Installer language / Язык установщика"
  echo "  [1] English"
  echo "  [2] Русский"
  echo -en "  choice / выбор (Enter — Русский): "
  read -r _hkz_lc
  case "$_hkz_lc" in
    1|en|EN|english|English) export HKZ_LANG=en ;;
    *) export HKZ_LANG=ru ;;
  esac
  echo ""
  if [ "${HKZ_LANG}" = en ]; then
    echo "  > Script language: English"
  else
    echo "  > Язык скрипта: Русский"
  fi
  echo ""
}

hkz_pick_lang_once() {
  [ -n "${HKZ_LANG_ASKED:-}" ] && return 0
  [ "${NONINTERACTIVE:-}" = true ] && export HKZ_LANG=ru HKZ_LANG_ASKED=1 && return 0
  local c="${1:-menu}"
  [ "$c" = "update" ] && [ "${2:-}" = "--quiet" ] && export HKZ_LANG=ru HKZ_LANG_ASKED=1 && return 0
  hkz_pick_lang
  export HKZ_LANG_ASKED=1
}

